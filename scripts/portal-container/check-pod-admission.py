#!/usr/bin/env python3
"""Exercise the installed SAW Pod policy with server-side dry-runs."""
import argparse
import copy
import json
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ("kubeconfig", "namespace", "gateway"):
        parser.add_argument("--" + option, required=True)
    parser.add_argument("--fixture-namespace", help="Optional source of matching stock PodSpecs for an isolated policy test")
    parser.add_argument("--sandbox-controller", default="system:serviceaccount:agent-sandbox-system:agent-sandbox-controller",
                        help="Agent Sandbox controller identity configured on the site")
    args = parser.parse_args()
    oc = ["oc", "--kubeconfig", args.kubeconfig, "-n", args.namespace, "--request-timeout=20s"]
    account = f"system:serviceaccount:{args.namespace}:{args.gateway}-gateway"
    target = json.loads(subprocess.check_output(oc + ["get", "pods", "-o", "json"]))["items"]
    if args.fixture_namespace:
        items = json.loads(subprocess.check_output(oc + ["-n", args.fixture_namespace, "get", "pods", "-o", "json"]))["items"]
    else:
        items = target

    def fixture(role):
        pod = next(p for p in items if p["metadata"].get("labels", {}).get("openshell.ai/boundary-role") == role)
        meta = {k: copy.deepcopy(pod["metadata"][k]) for k in ("name", "labels", "ownerReferences")}
        # A copied owner reference cannot confer permission to block owner deletion.
        for owner in meta["ownerReferences"]:
            owner.pop("blockOwnerDeletion", None)
        spec = copy.deepcopy(pod["spec"])
        spec.pop("nodeName", None)
        if args.fixture_namespace and args.fixture_namespace != args.namespace:
            spec.pop("imagePullSecrets", None)
            for container in [spec, *spec["containers"], *spec.get("initContainers", [])]:
                for field in ("runAsUser", "runAsGroup", "fsGroup", "seLinuxOptions", "supplementalGroups"):
                    container.get("securityContext", {}).pop(field, None)
        return {"apiVersion": "v1", "kind": "Pod", "metadata": meta, "spec": spec}

    def denied(label, command, *, obj=None, identity=account):
        caller = ["--as=" + identity, "--as-group=system:authenticated", "--as-group=system:serviceaccounts",
                  "--as-group=system:serviceaccounts:" + identity.split(":")[2]]
        result = subprocess.run(oc + caller + command + ["--dry-run=server"], text=True,
                                input=json.dumps(obj) if obj else None, capture_output=True)
        policy = ("saw-" + args.namespace + "-runtime")[:63].rstrip("-")
        if result.returncode == 0 or "ValidatingAdmissionPolicy" not in result.stderr or policy not in result.stderr:
            raise SystemExit(f"{label}: expected denial from {policy}: {result.stderr.strip()}")
        print(label + ": denied by the workspace Pod policy")

    workload = fixture("workload")
    denied("forged workload creator", ["create", "-f", "-"], obj=workload)
    workload["spec"]["initContainers"][0]["env"] = [{
        "name": "REVIEW", "valueFrom": {"secretKeyRef": {"name": "nonexistent-review-fixture", "key": "review"}}}]
    denied("unapproved workload generated by the Sandbox controller", ["create", "-f", "-"],
           obj=workload, identity=args.sandbox_controller)
    pod = fixture("supervisor")
    pod["spec"]["volumes"].append({"name": "review", "secret": {"secretName": "nonexistent-review-fixture"}})
    denied("unapproved supervisor Secret", ["create", "-f", "-"], obj=pod)
    unmarked = fixture("workload")
    unmarked["metadata"] = {"name": "saw-admission-negative-check"}
    unmarked["spec"]["serviceAccountName"] = "default"
    denied("unmarked Pod", ["create", "-f", "-"], obj=unmarked)
    patch = [{"op": "replace", "path": "/spec/containers/0/image", "value": "registry.k8s.io/pause:3.10"}]
    running = next(p for p in target if p["metadata"].get("labels", {}).get("openshell.ai/boundary-role") == "workload")
    role_patch = [{"op": "remove", "path": "/metadata/labels/openshell.ai~1boundary-role"}]
    denied("removal of workload identity", ["patch", "pod", running["metadata"]["name"], "--type=json",
                                           "-p", json.dumps(role_patch)])
    denied("workload image replacement", ["patch", "pod", running["metadata"]["name"], "--type=json",
                                          "-p", json.dumps(patch)])


if __name__ == "__main__":
    main()
